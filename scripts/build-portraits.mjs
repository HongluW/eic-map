// Embeds the portrait thumbnails in assets/portraits/ into src/EICMap.jsx as data URIs.
// Portraits are public-domain works from Wikimedia Commons; credits live in assets/portraits/credits.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'assets/portraits');
const TARGET = path.join(ROOT, 'src/EICMap.jsx');
const credits = JSON.parse(fs.readFileSync(path.join(DIR, 'credits.json'), 'utf8'));

const out = {};
for (const [k, c] of Object.entries(credits)) {
  const b64 = fs.readFileSync(path.join(DIR, `${k}.jpg`)).toString('base64');
  out[k] = { a: c.artist, w: c.file, f: c.frame, src: `data:image/jpeg;base64,${b64}` };
}
const block = `// @portraits-begin (generated by scripts/build-portraits.mjs — public-domain portraits via Wikimedia Commons)\nconst PORTRAITS = ${JSON.stringify(out)};\n// @portraits-end`;
let src = fs.readFileSync(TARGET, 'utf8');
src = /\/\/ @portraits-begin[\s\S]*?\/\/ @portraits-end/.test(src)
  ? src.replace(/\/\/ @portraits-begin[\s\S]*?\/\/ @portraits-end/, block)
  : src.replace('// @geo-begin', `${block}\n\n// @geo-begin`);
fs.writeFileSync(TARGET, src);
console.log('portraits', Object.keys(out).length, 'bytes', block.length);
